import React from 'react';
import { act, create } from 'react-test-renderer';
import { afterEach, expect, test, vi } from 'vitest';
import axios from 'axios';
import GlobalSearch from './GlobalSearch';
import ConvSearchBar from './ConvSearchBar';
import { TextButton } from '../ui-kit/Button';
const { translate } = vi.hoisted(()=>({translate:key=>key}));
vi.mock('axios',()=>({default:{get:vi.fn()}}));
vi.mock('../contexts/I18nContext',()=>({useI18n:()=>({t:translate})}));
vi.mock('../hooks/useOpenConversation',()=>({useOpenConversation:()=>({openContact:()=>{},openConversation:()=>{}})}));
vi.mock('./ConversationOpenFeedback',()=>({default:()=>null}));
vi.mock('./Avatar',()=>({default:()=>null}));
vi.mock('./GroupAvatar',()=>({GroupAvatar:()=>null}));
vi.mock('../ui-kit/Field',()=>({default:React.forwardRef(function TestField(props,ref) { return <input ref={ref} {...props}/>; })}));
let view;
const rows = Array.from({length:20},(_,i)=>({id:String(i),content:'matching message',sender_id:'sender',senderName:'QA'}));
afterEach(()=>{if(view) act(()=>view.unmount());view=null;vi.clearAllMocks();vi.useRealTimers();vi.unstubAllGlobals();});
test('global search exposes total and appends a second page through its visible control',async()=>{
  vi.useFakeTimers();
  axios.get.mockImplementation((url,{params}={})=>Promise.resolve({data:url==='/api/messages/search'?{results:params.offset? [{...rows[0],id:'last'}]:rows,total:21}:[]}));
  await act(async()=>{view=create(<GlobalSearch query="matching" onSelectConv={()=>{}} onNetworkSearch={()=>{}}/>);});
  await act(async()=>vi.runOnlyPendingTimersAsync());
  expect(view.root.findAllByProps({className:'gs-row'})).toHaveLength(20);
  const more=view.root.findAllByType(TextButton).find(button=>button.props.children==='gs.loadMore');
  await act(async()=>more.props.onClick());
  expect(view.root.findAllByProps({className:'gs-row'})).toHaveLength(21);
  expect(view.root.findAllByType(TextButton).some(button=>button.props.children==='gs.loadMore')).toBe(false);
  expect(axios.get.mock.calls.filter(call=>call[0]==='/api/messages/search')[1][1].params.offset).toBe(20);
});
test('conversation search offers more results and clears the previous query immediately',async()=>{
  vi.useFakeTimers();vi.stubGlobal('document',{activeElement:null,addEventListener:vi.fn(),removeEventListener:vi.fn()});
  axios.get.mockImplementation((_url,{params})=>Promise.resolve({data:params.offset?[{...rows[0],id:'last'}]:rows}));
  await act(async()=>{view=create(<ConvSearchBar convId="a" onJump={()=>{}} onClose={()=>{}}/>);});
  act(()=>view.root.findByType('input').props.onChange({target:{value:'matching'}}));
  await act(async()=>vi.runOnlyPendingTimersAsync());
  const more=view.root.findAllByType('button').find(button=>button.props.children==='gs.loadMore');
  await act(async()=>more.props.onClick());
  expect(view.root.findAllByProps({className:'conv-search-result'})).toHaveLength(21);
  act(()=>view.root.findByType('input').props.onChange({target:{value:'other'}}));
  expect(view.root.findAllByProps({className:'conv-search-result'})).toHaveLength(0);
});
