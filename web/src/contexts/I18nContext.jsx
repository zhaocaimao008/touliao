// 首屏只打包简体中文（默认语言，约占三分之一体积）；其余语言切换或启动时按需加载。
const LOCALE_LOADERS = {
  'en': () => import('../locales/en.js'),
  'zh-TW': () => import('../locales/zh-TW.js'),
};
const isSupported = l => l === 'zh-CN' || Object.prototype.hasOwnProperty.call(LOCALE_LOADERS, l);

/** 确保某语言词典已加载；失败（如离线拉不到 chunk）时返回 false，调用方回落简体。 */
export async function loadLocale(l) {
  if (translations[l]) return true;
  if (!isSupported(l)) return false;
  try {
    translations[l] = (await LOCALE_LOADERS[l]()).default;
    return true;
  } catch {
    return false;
  }
}

const savedLang = () => {
  // 校验存储值:旧版本/被篡改可能残留不支持的语言码(如 'ja'),会让 <html lang> 与词典错位
  const saved = localStorage.getItem('wc_lang');
  return isSupported(saved) ? saved : 'zh-CN';
};

/** 启动时（main.jsx 渲染前）预载上次选择的语言，避免首屏先闪一下简体。 */
export const preloadSavedLocale = () => loadLocale(savedLang());

const lookup = (lang, key, fallback) => {
  const dict = translations[lang] || translations['zh-CN'];
  return dict[key] || translations['zh-CN'][key] || fallback || key;
};

const I18nContext = createContext({ t: k => k, lang: 'zh-CN', setLang: () => {} });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(savedLang);
  // 词典异步到位后触发重渲染（预载失败或未预载时，先用简体兜底）
  const [, setLoadedTick] = useState(0);

  const setLang = async (l) => {
    if (!isSupported(l)) return;   // 只接受受支持的语言,避免切到空词典
    if (!(await loadLocale(l))) return;
    setLangState(l);
    localStorage.setItem('wc_lang', l);
    // Electron：同步语言到主进程，托盘菜单文案跟随切换
    if (window.__ELECTRON_CONFIG__) {
      window.electronAPI?.setTrayLocale?.(l).catch(() => {});
    }
  };

  const t = (key, fallback) => lookup(lang, key, fallback);

  useEffect(() => {
    document.documentElement.setAttribute('lang', lang);
    if (!translations[lang]) loadLocale(lang).then(ok => ok && setLoadedTick(n => n + 1));
    // Electron：启动时同步一次语言到主进程（托盘菜单初始文案）
    if (window.__ELECTRON_CONFIG__) {
      window.electronAPI?.setTrayLocale?.(lang).catch(() => {});
    }
  }, [lang]);

  return (
    <I18nContext.Provider value={{ t, lang, setLang, translations }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);

// class 组件（错误边界等）没有 Hook，无法用 useI18n()；这里给一个一次性快照式
// 取词函数，读取与 Provider 相同的 localStorage 语言设置。不订阅后续切换语言，
// 因为调用方（PanelBoundary/ChatWindowBoundary/ErrorBoundary）只在渲染出错这个
// 离散事件里取词，不需要语言切换时的实时刷新。词典未加载时回落简体。
export function getI18n() {
  const lang = savedLang();
  return (key, fallback) => lookup(lang, key, fallback);
}
